export function register(ctx: Ctx): void {
  ctx.handle('cron:status', async (serverId: string): Promise<CronStatus> => {
    const ssh = ctx.ssh(serverId)
    const script = `
echo __INSTALLED; command -v crontab >/dev/null 2>&1 && echo yes || echo no
echo __ACTIVE; a=no; for u in ${cronServiceNames()}; do if systemctl is-active --quiet $u 2>/dev/null; then a=yes; break; fi; done; if [ "$a" = no ]; then (pgrep -x cron >/dev/null 2>&1 || pgrep -x crond >/dev/null 2>&1) && a=yes; fi; echo $a
echo __TZ; date +%z; date +%Z; date -u +%Y-%m-%dT%H:%M:%SZ
echo __USERS; getent passwd 2>/dev/null | awk -F: '($3==0 || $3>=1000) && $3<65534 && $7 !~ /(nologin|false|sync|halt|shutdown)$/ {print $1}'
echo __END`
    const r = await ssh.exec(script, { timeoutMs: 20000 })
    const sec = parseSections(r.stdout)
    const loginUser = ssh.os?.user ?? ssh.profile.username
    const others = (sec.USERS ?? []).map((l) => l.trim()).filter((u) => u && u !== loginUser && /^[A-Za-z0-9][A-Za-z0-9_.@-]*$/.test(u))
    const sorted = [...new Set(others)].sort((a, b) => (a === 'root' ? -1 : b === 'root' ? 1 : a.localeCompare(b)))
    const tz = (sec.TZ ?? []).map((l) => l.trim())
    return {
      installed: (sec.INSTALLED?.[0] ?? '').trim() === 'yes',
      cronActive: (sec.ACTIVE ?? []).some((l) => l.trim() === 'yes'),
      serverTz: tz[0] || '+0000',
      serverTzName: tz[1] || 'UTC',
      serverNow: tz[2] || new Date().toISOString(),
      users: [loginUser, ...sorted],
      loginUser,
      isRoot: ssh.os?.isRoot ?? false,
      sudoAvailable: ssh.os?.sudoAvailable ?? false
    }
  })

  ctx.handle('cron:list', async (serverId: string, user: string): Promise<CronListResult> => {
    assertSafeName(user, 'user')
    const ssh = ctx.ssh(serverId)
    const raw = await readCrontab(ssh, user)
    const parsed = parseCrontab(raw, user)
    return { jobs: parsed.jobs, variables: parsed.variables, raw }
  })

  ctx.handle('cron:save', async (serverId: string, user: string, input: CronSaveInput) => {
    assertSafeName(user, 'user')
    if (!input || !Array.isArray(input.jobs) || !Array.isArray(input.variables)) throw new Error('Invalid crontab payload')
    const ssh = ctx.ssh(serverId)
    const current = await readCrontab(ssh, user)
    const { header } = parseCrontab(current, user)
    const text = serializeCrontab(header, input.variables, input.jobs)
    await backupCrontab(ssh, user, current)
    await installCrontab(ssh, user, text)
    ctx.audit(serverId, 'cron.save', `${user}: ${input.jobs.length} job(s), ${input.variables.length} variable(s)`)
    return text
  })

  ctx.handle('cron:saveRaw', async (serverId: string, user: string, text: string) => {
    assertSafeName(user, 'user')
    if (typeof text !== 'string') throw new Error('Invalid crontab text')
    const ssh = ctx.ssh(serverId)
    const current = await readCrontab(ssh, user)
    const normalized = text.replace(/\r\n?/g, '\n').replace(/\n*$/, '\n')
    await backupCrontab(ssh, user, current)
    if (!normalized.trim()) {
      // Empty text = remove the crontab entirely.
      const self = isSelf(ssh, user)
      const r = await ssh.exec(self ? 'crontab -r' : `crontab -r -u ${shq(user)}`, { sudo: !self })
      if (r.code !== 0 && !/no crontab/i.test(r.stderr)) throw new Error(r.stderr.trim() || 'crontab -r failed')
    } else {
      await installCrontab(ssh, user, normalized)
    }
    ctx.audit(serverId, 'cron.saveRaw', user)
  })

  ctx.handle('cron:runNow', async (serverId: string, user: string, command: string) => {
    assertSafeName(user, 'user')
    const cmd = oneLine(command)
    if (!cmd) throw new Error('Empty command')
    const ssh = ctx.ssh(serverId)
    const self = isSelf(ssh, user)
    const title = `Run cron job: ${cmd.length > 60 ? cmd.slice(0, 57) + '…' : cmd}`
    const { id } = ctx.tasks.start(title, serverId, async (h) => {
      h.log(`$ ${cmd}   (as ${user})`)
      const shellCmd = self
        ? `sh -c ${shq(cmd)}`
        : `if command -v runuser >/dev/null 2>&1; then runuser -u ${shq(user)} -- sh -c ${shq(cmd)}; else su - ${shq(user)} -s /bin/sh -c ${shq(cmd)}; fi`
      const r = await ssh.exec(shellCmd, { sudo: !self, timeoutMs: 0, signal: h.signal, onStdout: (c) => h.append(c), onStderr: (c) => h.append(c) })
      h.log(`\n[exit code ${r.code}]`)
      if (r.code !== 0) throw new Error(`Command exited with code ${r.code}`)
    })
    ctx.audit(serverId, 'cron.runNow', `${user}: ${cmd}`)
    return id
  })

  ctx.handle('cron:log', async (serverId: string, lines = 200): Promise<string[]> => {
    const n = Math.max(10, Math.min(5000, Math.floor(Number(lines) || 200)))
    const ssh = ctx.ssh(serverId)
    const script = `out=$(journalctl -q -u cron -u crond -u cronie --no-pager -n ${n} -o short-iso 2>/dev/null); if [ -n "$out" ]; then printf '%s\\n' "$out"; else { grep -h -E 'CRON|crond' /var/log/cron /var/log/syslog /var/log/messages 2>/dev/null || cat /var/log/cron.log 2>/dev/null; } | tail -n ${n}; fi`
    const r = await ssh.exec(script, { sudo: ssh.os?.sudoAvailable ?? false, timeoutMs: 30000 }).catch(() => ssh.exec(script, { timeoutMs: 30000 }))
    return r.stdout.split('\n').filter((l) => l.trim())
  })

  ctx.handle('cron:system', async (serverId: string): Promise<CronSystemResult> => {
    const ssh = ctx.ssh(serverId)
    const dirLoop = SYSTEM_DIRS.map(
      (d) =>
        `echo "__DIR ${d}"; if [ -d ${d} ]; then echo exists; for f in ${d}/*; do [ -f "$f" ] || continue; x=n; [ -x "$f" ] && x=y; s=$(stat -c %s "$f" 2>/dev/null || wc -c < "$f"); printf '%s\\t%s\\t%s\\n' "$(basename "$f")" "$x" "$s"; done; fi`
    ).join('\n')
    const script = `echo __CRONTAB; cat /etc/crontab 2>/dev/null\n${dirLoop}\necho __END`
    const r = await ssh.exec(script, { sudo: ssh.os?.sudoAvailable ?? false, timeoutMs: 30000 }).catch(() => ssh.exec(script, { timeoutMs: 30000 }))
    const sec = parseSections(r.stdout)
    const crontabLines = sec.CRONTAB ?? []
    const crontabText = crontabLines.join('\n')
    const jobCount = crontabLines.filter((l) => {
      const t = l.trim()
      if (!t || t.startsWith('#')) return false
      const parts = t.split(/\s+/)
      return (t.startsWith('@') && parts.length >= 3) || (parts.length >= 7 && looksLikeCronSchedule(parts.slice(0, 5).join(' ')))
    }).length
    const dirs: CronSystemDir[] = SYSTEM_DIRS.map((dir) => {
      const lines = sec[`DIR ${dir}`] ?? []
      const exists = lines[0]?.trim() === 'exists'
      const files = lines
        .slice(1)
        .map((l) => l.split('\t'))
        .filter((p) => p.length >= 2 && p[0])
        .map((p) => ({ name: p[0], path: `${dir}/${p[0]}`, executable: p[1] === 'y', size: Number(p[2]) || 0 }))
        .sort((a, b) => a.name.localeCompare(b.name))
      return { dir, exists, files }
    })
    return {
      crontab: { path: '/etc/crontab', exists: crontabText.trim().length > 0, lines: crontabLines.filter((l) => l.trim()).length, jobs: jobCount, preview: crontabText },
      dirs
    }
  })

  ctx.handle('cron:readFile', async (serverId: string, path: string): Promise<string> => {
    const p = assertSystemCronPath(path)
    const ssh = ctx.ssh(serverId)
    const r = await ssh.exec(`head -c 512000 ${shq(p)}`, { sudo: ssh.os?.sudoAvailable ?? false, timeoutMs: 20000 }).catch(() => ssh.exec(`head -c 512000 ${shq(p)}`, { timeoutMs: 20000 }))
    if (r.code !== 0) throw new Error(r.stderr.trim() || `Cannot read ${p}`)
    return r.stdout
  })

  ctx.handle('cron:systemdTimers', async (serverId: string): Promise<SystemdTimer[]> => {
    const ssh = ctx.ssh(serverId)
    if (ssh.os && !ssh.os.hasSystemd) return []
    const r = await ssh.exec('systemctl list-timers --all --no-pager --output=json 2>/dev/null || systemctl list-timers --all --no-pager --no-legend --plain 2>/dev/null', { timeoutMs: 20000 })
    const out = r.stdout.trim()
    if (!out) return []
    if (out.startsWith('[')) {
      try {
        const arr = JSON.parse(out) as Record<string, unknown>[]
        const s = (v: unknown): string => (v === null || v === undefined ? '' : typeof v === 'number' ? new Date(v > 1e12 ? v / 1000 : v).toISOString() : String(v))
        const dur = (v: unknown): string => (typeof v === 'number' ? fmtElapsed(v / 1e6) : s(v))
        return arr.map((t) => ({ next: s(t.next), left: dur(t.left), last: s(t.last), passed: dur(t.passed), unit: s(t.unit), activates: s(t.activates) }))
      } catch {
        /* fall through to plain parsing */
      }
    }
    // Plain fallback: the last two tokens are UNIT and ACTIVATES; the rest is the time columns.
    return out
      .split('\n')
      .filter((l) => l.trim())
      .map((l) => {
        const parts = l.trim().split(/\s+/)
        const activates = parts.pop() ?? ''
        const unit = parts.pop() ?? ''
        return { next: parts.join(' '), left: '', last: '', passed: '', unit, activates }
      })
  })

  ctx.handle('cron:install', async (serverId: string) => {
    const ssh = ctx.ssh(serverId)
    const pkg = cronPackage(ssh)
    const { id } = ctx.tasks.start(`Install ${pkg}`, serverId, async (h) => {
      await runPkg(ssh, installCmd(ssh, [pkg]), { signal: h.signal, onStdout: (c) => h.append(c), onStderr: (c) => h.append(c) })
      h.log('Enabling the cron service…')
      await ssh.sudo(`for u in ${cronServiceNames()}; do systemctl enable --now $u 2>/dev/null && break; done; true`)
      ctx.audit(serverId, 'cron.install', pkg)
    })
    return id
  })

  ctx.handle('cron:startService', async (serverId: string) => {
    const ssh = ctx.ssh(serverId)
    const r = await ssh.sudo(`for u in ${cronServiceNames()}; do if systemctl cat $u >/dev/null 2>&1; then systemctl enable --now $u && exit 0; fi; done; (service cron start || service crond start) 2>&1`)
    if (r.code !== 0) throw new Error((r.stderr + r.stdout).trim() || 'Could not start the cron service')
    ctx.audit(serverId, 'cron.start')
  })
}
