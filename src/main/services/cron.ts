function isSelf(ssh: SshClient, user: string): boolean {
  return user === (ssh.os?.user ?? ssh.profile.username)
}

/** Read a user's crontab. Empty string when the user has none. */
async function readCrontab(ssh: SshClient, user: string): Promise<string> {
  const self = isSelf(ssh, user)
  const r = await ssh.exec(self ? 'crontab -l' : `crontab -l -u ${shq(user)}`, { sudo: !self, timeoutMs: 20000 })
  if (r.code === 0) return r.stdout
  const err = (r.stderr + r.stdout).trim()
  if (/no crontab for/i.test(err)) return ''
  if (/not found|No such file/i.test(err) && /crontab/.test(err)) throw new Error('crontab is not installed on this server')
  throw new Error(err || `crontab -l failed (exit ${r.code})`)
}

async function backupCrontab(ssh: SshClient, user: string, current: string): Promise<void> {
  if (!current.trim()) return
  const ts = new Date().toISOString().replace(/[:.]/g, '-')
  const b64 = Buffer.from(current, 'utf8').toString('base64')
  const dest = `${BACKUP_DIR}/crontab-${user}-${ts}`
  const cmd = `mkdir -p ${BACKUP_DIR} && printf %s ${shq(b64)} | base64 -d > ${shq(dest)} && chmod 600 ${shq(dest)}`
  try {
    if (ssh.os?.sudoAvailable) {
      const r = await ssh.sudo(cmd, { timeoutMs: 15000 })
      if (r.code === 0) return
    }
  } catch {
    /* fall through to home-dir backup */
  }
  // Fallback for logins without root: keep the copy in the home directory.
  await ssh.exec(`mkdir -p ~/.serversysops/backups && printf %s ${shq(b64)} | base64 -d > ~/.serversysops/backups/crontab-${shq(user)}-${ts}`, { timeoutMs: 15000 }).catch(() => undefined)
}

/** Install a crontab from text; crontab(1) validates the syntax and refuses bad files. */
async function installCrontab(ssh: SshClient, user: string, text: string): Promise<void> {
  const self = isSelf(ssh, user)
  const r = await ssh.exec(self ? 'crontab -' : `crontab -u ${shq(user)} -`, { sudo: !self, stdin: text, timeoutMs: 20000 })
  if (r.code !== 0) {
    const msg = (r.stderr + r.stdout).trim() || `crontab exited with ${r.code}`
    throw new Error(msg.replace(/^"-":/gm, 'line').replace(/^(\d+): /gm, 'line $1: '))
  }
}

function cronServiceNames(): string {
  return 'cron crond cronie'
}

function cronPackage(ssh: SshClient): string {
  switch (ssh.os?.pkgManager) {
    case 'apt':
      return 'cron'
    case 'zypper':
      return 'cron'
    default:
      return 'cronie'
  }
}

function assertSystemCronPath(p: string): string {
  assertAbsPath(p)
  if (p.includes('..') || /[\s'"`$\\]/.test(p)) throw new Error(`Invalid path: ${p}`)
  if (p === '/etc/crontab') return p
  if (/^\/etc\/cron\.(d|hourly|daily|weekly|monthly)\/[^/]+$/.test(p)) return p
  throw new Error('Only files under /etc/cron* can be read here')
}

function parseSections(stdout: string): Record<string, string[]> {
  const sec: Record<string, string[]> = {}
  let cur = ''
  for (const line of stdout.split('\n')) {
    const m = line.match(/^__([A-Z]+)(?: (.*))?$/)
    if (m) {
      cur = m[2] ? `${m[1]} ${m[2]}` : m[1]
      sec[cur] = []
    } else if (cur) sec[cur].push(line)
  }
  return sec
}

