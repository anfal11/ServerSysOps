const BACKUP_DIR = '/var/backups/serversysops'
const SYSTEM_DIRS = ['/etc/cron.d', '/etc/cron.daily', '/etc/cron.weekly', '/etc/cron.hourly', '/etc/cron.monthly']
const VAR_RE = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/

/* ------------------------------------------------------------------ */
/* Crontab text <-> structure                                          */
/* ------------------------------------------------------------------ */

interface ParsedCrontab {
  header: string[]
  variables: CronVariable[]
  jobs: CronJob[]
}

/** Split a job line into schedule and command. Returns null when it is not a job. */
function splitJobLine(line: string): { schedule: string; command: string } | null {
  const t = line.trim()
  if (!t || t.startsWith('#')) return null
  if (t.startsWith('@')) {
    const m = t.match(/^(@\w+)\s+(.+)$/)
    if (!m || !looksLikeCronSchedule(m[1])) return null
    return { schedule: m[1].toLowerCase(), command: m[2].trim() }
  }
  const parts = t.split(/\s+/)
  if (parts.length < 6) return null
  const schedule = parts.slice(0, 5).join(' ')
  if (!looksLikeCronSchedule(schedule)) return null
  // Command is everything after the 5th field, keeping its inner spacing.
  let idx = 0
  for (let i = 0; i < 5; i++) {
    idx = t.indexOf(parts[i], idx) + parts[i].length
  }
  return { schedule, command: t.slice(idx).trim() }
}

function isHeaderBlock(lines: string[]): boolean {
  const joined = lines.join('\n')
  return /DO NOT EDIT THIS FILE|Edit this file to introduce tasks|m h\s+dom mon dow|crontab -e|installed on|Cron version/i.test(joined)
}

export function parseCrontab(text: string, user: string): ParsedCrontab {
  const lines = text.replace(/\r\n?/g, '\n').split('\n')
  const header: string[] = []
  const variables: CronVariable[] = []
  const jobs: CronJob[] = []
  let pending: string[] = [] // comment lines waiting for a job
  let pendingDisabled = false
  let sawContent = false
  let i = 0

  // Leading comment block: header when it is followed by a blank line or looks like a generated header.
  while (i < lines.length && lines[i].trim().startsWith('#') && lines[i].trim() !== CRON_DISABLED_MARKER) i++
  if (i > 0) {
    const block = lines.slice(0, i)
    const followedByBlank = i >= lines.length || lines[i].trim() === ''
    if (followedByBlank || isHeaderBlock(block)) {
      header.push(...block.map((l) => l.trimEnd()))
    } else {
      i = 0
    }
  }

  const pushJob = (schedule: string, command: string, enabled: boolean): void => {
    const comment = pending.length ? pending.map((c) => c.replace(/^#\s?/, '')).join('\n') : undefined
    jobs.push({ index: jobs.length, schedule, command, comment, enabled, user })
    pending = []
    pendingDisabled = false
  }

  for (; i < lines.length; i++) {
    const raw = lines[i]
    const t = raw.trim()
    if (!t) {
      pending = []
      pendingDisabled = false
      continue
    }
    sawContent = true
    if (t === CRON_DISABLED_MARKER) {
      pendingDisabled = true
      continue
    }
    if (t.startsWith('#')) {
      const body = t.replace(/^#\s?/, '')
      const job = splitJobLine(body)
      if (job && (pendingDisabled || isStrictNumericCronSchedule(job.schedule))) {
        pushJob(job.schedule, job.command, false)
        continue
      }
      if (pendingDisabled) pendingDisabled = false
      pending.push(t)
      continue
    }
    const job = splitJobLine(t)
    if (job) {
      pushJob(job.schedule, job.command, true)
      continue
    }
    const vm = t.match(VAR_RE)
    if (vm) {
      variables.push({ key: vm[1], value: vm[2].trim() })
      pending = []
      pendingDisabled = false
      continue
    }
    // Unknown line: keep as a comment attached to the next job so nothing is silently lost.
    pending.push('# ' + t)
  }
  void sawContent
  return { header, variables, jobs }
}

function oneLine(s: string): string {
  return String(s ?? '')
    .replace(/[\r\n]+/g, ' ')
    .trim()
}

export function serializeCrontab(header: string[], variables: CronVariable[], jobs: CronSaveInput['jobs']): string {
  const out: string[] = []
  const hdr = header.length ? header : ['# Crontab managed with ServerSysOps. Edit here or with `crontab -e`.', '# Lines after "# serversysops:disabled" are jobs that are switched off.']
  out.push(...hdr)
  out.push('')
  if (variables.length) {
    for (const v of variables) {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(v.key)) throw new Error(`Invalid variable name: ${v.key}`)
      out.push(`${v.key}=${oneLine(v.value)}`)
    }
    out.push('')
  }
  for (const j of jobs) {
    const schedule = oneLine(j.schedule).replace(/\s+/g, ' ')
    const command = oneLine(j.command)
    if (!looksLikeCronSchedule(schedule)) throw new Error(`Invalid schedule: "${schedule}"`)
    if (!command) throw new Error('A job needs a command')
    if (j.comment) for (const c of j.comment.split('\n')) out.push(c.trim().startsWith('#') ? c.trim() : `# ${c.trim()}`)
    if (j.enabled) out.push(`${schedule} ${command}`)
    else {
      out.push(CRON_DISABLED_MARKER)
      out.push(`# ${schedule} ${command}`)
    }
    out.push('')
  }
  while (out.length && out[out.length - 1] === '') out.pop()
  return out.join('\n') + '\n'
}

